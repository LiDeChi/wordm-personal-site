function makeGlyph(strokes, advance = 1.02) {
  return {
    advance,
    strokes: strokes.map((stroke) =>
      stroke.map(([x, y]) => ({
        x,
        y,
      })),
    ),
  };
}

function fromSegments(names, advance = 1.02) {
  return makeGlyph(names.map((name) => SEGMENTS[name]), advance);
}

function transformGlyph(glyph, transform) {
  const scaleX = transform.scaleX ?? 1;
  const scaleY = transform.scaleY ?? 1;
  const offsetX = transform.offsetX ?? 0;
  const offsetY = transform.offsetY ?? 0;
  const advanceScale = transform.advanceScale ?? 1;

  return {
    advance: glyph.advance * advanceScale,
    strokes: glyph.strokes.map((stroke) =>
      stroke.map((point) => ({
        x: point.x * scaleX + offsetX,
        y: point.y * scaleY + offsetY,
      })),
    ),
  };
}

function cloneGlyph(glyph) {
  return {
    advance: glyph.advance,
    strokes: glyph.strokes.map((stroke) =>
      stroke.map((point) => ({
        x: point.x,
        y: point.y,
      })),
    ),
  };
}

function mergeGlyphs(glyphs, advance = 1.02) {
  return {
    advance,
    strokes: glyphs.flatMap((glyph) =>
      glyph.strokes.map((stroke) =>
        stroke.map((point) => ({
          x: point.x,
          y: point.y,
        })),
      ),
    ),
  };
}

