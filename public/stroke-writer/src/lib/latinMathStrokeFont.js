export function getLatinMathGlyph(char) {
  const glyph = GLYPHS[char];
  return glyph ? cloneGlyph(glyph) : null;
}

export function hasLatinMathGlyph(char) {
  return Object.prototype.hasOwnProperty.call(GLYPHS, char);
}

export function getFormulaGlyph(char) {
  const glyph = FORMULA_GLYPHS[char] ?? GLYPHS[char] ?? GLYPHS["?"];
  return cloneGlyph(glyph);
}

export function hasFormulaGlyph(char) {
  return Object.prototype.hasOwnProperty.call(FORMULA_GLYPHS, char) || Object.prototype.hasOwnProperty.call(GLYPHS, char);
}
